"""
Document Service.
=================
Generates deterministic proof-of-insurance PDF documents for specific CoverageVersion
records using ReportLab. Documents prominently display DEMO ONLY watermarks and disclaimers.
"""

import io
from datetime import UTC, datetime

from fastapi import HTTPException, status
from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.pdfgen import canvas
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy.orm import selectinload

from app.core.logging import get_logger, mask_vin
from app.models import CoverageVersion
from app.services.audit_service import record_audit_event

logger = get_logger("service.document")


async def generate_proof_of_insurance_pdf(
    session: AsyncSession,
    coverage_version_id: int,
) -> bytes:
    """
    Generate an official DEMO ONLY proof of insurance PDF for a specific CoverageVersion.
    Records a PROOF_OF_INSURANCE_GENERATED audit event upon generation.
    """
    logger.info("proof_generation_started", coverage_version_id=coverage_version_id)
    query = (
        select(CoverageVersion)
        .options(
            selectinload(CoverageVersion.policy),
            selectinload(CoverageVersion.vehicle),
        )
        .where(CoverageVersion.id == coverage_version_id)
    )
    result = await session.execute(query)
    cov = result.scalars().first()

    if not cov:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Coverage Version #{coverage_version_id} not found.",
        )

    buffer = io.BytesIO()
    c = canvas.Canvas(buffer, pagesize=letter, pageCompression=0)
    width, height = letter

    # ─── Watermark Background ───────────────────────────────────────────────
    c.saveState()
    c.setFont("Helvetica-Bold", 40)
    c.setFillColor(colors.Color(0.85, 0.85, 0.85, alpha=0.35))
    c.translate(width / 2, height / 2)
    c.rotate(35)
    c.drawCentredString(0, 50, "DEMO ONLY")
    c.drawCentredString(0, -10, "NOT A REAL INSURANCE DOCUMENT")
    c.restoreState()

    # ─── Top Header Banner ──────────────────────────────────────────────────
    c.setFillColor(colors.HexColor("#1e293b"))  # Slate-800
    c.rect(36, height - 90, width - 72, 54, fill=1, stroke=0)

    c.setFillColor(colors.white)
    c.setFont("Helvetica-Bold", 16)
    c.drawString(50, height - 60, "HISTORICAL COVERAGE EXPLORER — DEMO CERTIFICATE")
    c.setFont("Helvetica", 9)
    c.drawString(
        50,
        height - 76,
        "Synthetic Demonstration Record • Point-in-Time Temporal Verification",
    )

    # ─── Prominent Warning Banner ───────────────────────────────────────────
    c.setFillColor(colors.HexColor("#fef3c7"))  # Amber-100
    c.setStrokeColor(colors.HexColor("#f59e0b"))  # Amber-500
    c.setLineWidth(1)
    c.rect(36, height - 145, width - 72, 45, fill=1, stroke=1)

    c.setFillColor(colors.HexColor("#92400e"))  # Amber-800
    c.setFont("Helvetica-Bold", 11)
    c.drawString(50, height - 118, "DEMO ONLY — NOT A REAL INSURANCE DOCUMENT")
    c.setFont("Helvetica", 8.5)
    c.drawString(
        50,
        height - 132,
        "This certificate is generated by Historical Coverage Explorer using "
        "synthetic demonstration data. It has no legal validity.",
    )

    # ─── Policy Identification Section ─────────────────────────────────────
    y = height - 175
    c.setFont("Helvetica-Bold", 12)
    c.setFillColor(colors.HexColor("#0f172a"))
    c.drawString(50, y, "1. POLICY IDENTIFICATION")

    y -= 8
    c.setStrokeColor(colors.HexColor("#cbd5e1"))
    c.line(50, y, width - 50, y)

    y -= 18
    c.setFont("Helvetica-Bold", 9.5)
    c.setFillColor(colors.HexColor("#475569"))
    c.drawString(50, y, "Policy Number:")
    c.setFont("Helvetica", 9.5)
    c.setFillColor(colors.HexColor("#0f172a"))
    c.drawString(160, y, cov.policy.policy_number)

    c.setFont("Helvetica-Bold", 9.5)
    c.setFillColor(colors.HexColor("#475569"))
    c.drawString(340, y, "Policy Status:")
    c.setFont("Helvetica", 9.5)
    c.setFillColor(colors.HexColor("#059669"))  # Emerald
    c.drawString(440, y, cov.policy.status)

    y -= 18
    c.setFont("Helvetica-Bold", 9.5)
    c.setFillColor(colors.HexColor("#475569"))
    c.drawString(50, y, "Named Insured:")
    c.setFont("Helvetica", 9.5)
    c.setFillColor(colors.HexColor("#0f172a"))
    c.drawString(160, y, cov.policy.customer_name)

    c.setFont("Helvetica-Bold", 9.5)
    c.setFillColor(colors.HexColor("#475569"))
    c.drawString(340, y, "Document Version:")
    c.setFont("Helvetica", 9.5)
    c.setFillColor(colors.HexColor("#0f172a"))
    c.drawString(440, y, f"Version #{cov.id} ({cov.version_label})")

    # ─── Covered Vehicle Section ───────────────────────────────────────────
    y -= 32
    c.setFont("Helvetica-Bold", 12)
    c.setFillColor(colors.HexColor("#0f172a"))
    c.drawString(50, y, "2. COVERED VEHICLE")

    y -= 8
    c.line(50, y, width - 50, y)

    y -= 18
    c.setFont("Helvetica-Bold", 9.5)
    c.setFillColor(colors.HexColor("#475569"))
    c.drawString(50, y, "Vehicle:")
    c.setFont("Helvetica", 9.5)
    c.setFillColor(colors.HexColor("#0f172a"))
    c.drawString(160, y, f"{cov.vehicle.year} {cov.vehicle.make} {cov.vehicle.model}")

    c.setFont("Helvetica-Bold", 9.5)
    c.setFillColor(colors.HexColor("#475569"))
    c.drawString(340, y, "Masked VIN:")
    c.setFont("Helvetica-Bold", 9.5)
    c.setFillColor(colors.HexColor("#0f172a"))
    masked_vin = f"••••-{cov.vehicle.vin[-3:]} (SYNTHETIC)"
    c.drawString(440, y, masked_vin)

    y -= 18
    c.setFont("Helvetica-Bold", 9.5)
    c.setFillColor(colors.HexColor("#475569"))
    c.drawString(50, y, "Vehicle Added Date:")
    c.setFont("Helvetica", 9.5)
    c.setFillColor(colors.HexColor("#0f172a"))
    c.drawString(160, y, cov.vehicle.added_at.strftime("%B %d, %Y"))

    c.setFont("Helvetica-Bold", 9.5)
    c.setFillColor(colors.HexColor("#475569"))
    c.drawString(340, y, "Lifecycle Status:")
    c.setFont("Helvetica", 9.5)
    if cov.vehicle.removed_at:
        c.setFillColor(colors.HexColor("#d97706"))  # Amber
        c.drawString(440, y, f"Past / Removed {cov.vehicle.removed_at.strftime('%b %d, %Y')}")
    else:
        c.setFillColor(colors.HexColor("#059669"))
        c.drawString(440, y, "Active on Policy")

    # ─── Effective Coverage Interval & Terms ───────────────────────────────
    y -= 32
    c.setFont("Helvetica-Bold", 12)
    c.setFillColor(colors.HexColor("#0f172a"))
    c.drawString(50, y, "3. EFFECTIVE COVERAGE INTERVAL & TERMS")

    y -= 8
    c.line(50, y, width - 50, y)

    y -= 18
    c.setFont("Helvetica-Bold", 9.5)
    c.setFillColor(colors.HexColor("#475569"))
    c.drawString(50, y, "Coverage Effective:")
    c.setFont("Helvetica", 9.5)
    c.setFillColor(colors.HexColor("#0f172a"))
    c.drawString(160, y, f"{cov.valid_from.strftime('%B %d, %Y')} (inclusive)")

    c.setFont("Helvetica-Bold", 9.5)
    c.setFillColor(colors.HexColor("#475569"))
    c.drawString(340, y, "Coverage Termination:")
    c.setFont("Helvetica", 9.5)
    if cov.valid_to:
        c.drawString(470, y, f"{cov.valid_to.strftime('%B %d, %Y')} (exclusive)")
    else:
        c.drawString(470, y, "Active / Indefinite")

    y -= 18
    c.setFont("Helvetica-Bold", 9.5)
    c.setFillColor(colors.HexColor("#475569"))
    c.drawString(50, y, "Coverage Type:")
    c.setFont("Helvetica", 9.5)
    c.drawString(160, y, cov.coverage_type)

    y -= 18
    c.setFont("Helvetica-Bold", 9.5)
    c.drawString(50, y, "Liability Limit:")
    c.setFont("Helvetica", 9.5)
    c.drawString(160, y, f"${cov.liability_limit:,.2f}")

    c.setFont("Helvetica-Bold", 9.5)
    c.drawString(340, y, "Deductible:")
    c.setFont("Helvetica", 9.5)
    c.drawString(470, y, f"${cov.deductible:,.2f}")

    # ─── Table of Verification Notes ───────────────────────────────────────
    y -= 38
    c.setFillColor(colors.HexColor("#f8fafc"))
    c.rect(50, y - 75, width - 100, 75, fill=1, stroke=1)

    c.setFillColor(colors.HexColor("#334155"))
    c.setFont("Helvetica-Bold", 9)
    c.drawString(60, y - 16, "TEMPORAL INTERVAL SPECIFICATION & TECHNICAL VALIDATION")

    c.setFont("Helvetica", 8)
    c.drawString(
        60,
        y - 32,
        "• Interval semantics: [valid_from, valid_to). Coverage was active from valid_from "
        "through 23:59:59 prior to valid_to.",
    )
    c.drawString(
        60,
        y - 46,
        "• Example: Coverage with valid_from 2026-01-01 and valid_to 2026-01-15 is active "
        "Jan 1 through Jan 14 inclusive.",
    )
    c.drawString(
        60,
        y - 60,
        "• Historical queries evaluate date_of_loss against this interval regardless of "
        "subsequent vehicle removal dates.",
    )

    # ─── Footer & Metadata ─────────────────────────────────────────────────
    now_utc = datetime.now(UTC)
    c.setFont("Helvetica", 8)
    c.setFillColor(colors.HexColor("#64748b"))
    c.drawString(
        50,
        48,
        f"Generated At: {now_utc.strftime('%Y-%m-%d %H:%M:%S UTC')} • CoverageVersion ID: {cov.id}",
    )
    c.drawString(
        50,
        36,
        "Disclaimer: This document is generated from synthetic prototype data "
        "and has no legal validity.",
    )

    c.showPage()
    c.save()

    pdf_bytes = buffer.getvalue()
    buffer.close()

    # Record durable audit event
    await record_audit_event(
        session=session,
        event_type="PROOF_OF_INSURANCE_GENERATED",
        policy_id=cov.policy_id,
        vehicle_id=cov.vehicle_id,
        metadata_json={
            "coverage_version_id": cov.id,
            "version_label": cov.version_label,
            "valid_from": cov.valid_from.isoformat(),
            "valid_to": cov.valid_to.isoformat() if cov.valid_to else None,
            "generated_at": now_utc.isoformat(),
        },
    )
    await session.commit()

    logger.info(
        "proof_generated",
        coverage_version_id=cov.id,
        vehicle_id=cov.vehicle_id,
        masked_vin=mask_vin(cov.vehicle.vin),
        size_bytes=len(pdf_bytes),
    )

    return pdf_bytes
